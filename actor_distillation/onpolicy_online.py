"""
FULLY-ONLINE on-policy selection-distillation (2 GPUs, streaming).

  GPU0: ACTOR  (MolmoWeb-4B + LoRA, trainable + optimizer)  -- generates AND trains
  GPU1: SELECTOR (merged all-linear arbiter, vLLM, frozen)   -- picks best-of-5

Loop, per batch of states (cycling the pool):
  1. actor.generate(n=5, temp 1.0)         on-policy candidates from CURRENT weights  [GPU0]
  2. selector picks best-of-5 per state     (catts_vision_select_v2 via vLLM)         [GPU1]
  3. one SFT gradient step on {prompt -> selected action}                              [GPU0]
  -> next batch is generated by the just-updated actor (fully on-policy).

This is a SCAFFOLD: structurally faithful, not yet GPU-smoke-tested. The device split,
the molmo generate/train interleave, and selection latency are the parts to validate first
(run with --smoke for a few batches).

Env: ACTOR_MODEL, ACTOR_REVISION, ARBITER_DIR, STATES, OUT, BATCH, LR, EPOCHS,
     LORA_TARGETS, LORA_EXCLUDE, KL_COEF (0 = off; >0 anchors to the frozen base actor).
"""
